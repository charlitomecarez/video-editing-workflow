// Copies [brand] from config.toml / config.local.toml into src/brand.ts,
// so animations use the same colors and fonts as the thumbnails and slates.
import {execFileSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';
const cfg = JSON.parse(
  execFileSync('python3', ['../tools/vwconfig.py', 'show'], {encoding: 'utf8'}),
);
const b = cfg.brand ?? {};
const brand = {
  bg: b.bg ?? '#0d1117',
  bg2: b.bg2 ?? '#161b22',
  fg: b.fg ?? '#ffffff',
  accent: b.accent ?? '#ffd400',
  accent2: b.accent2 ?? '#00e5ff',
  fontHeading: b.font_heading ?? 'Arial Black',
  fontBody: b.font_body ?? 'Helvetica Neue',
  fontCode: b.font_code ?? 'Menlo',
};
writeFileSync(
  'src/brand.ts',
  `// Generated by sync-brand.mjs from config.toml. Don't edit; change [brand] instead.\nexport const brand = ${JSON.stringify(brand, null, 2)} as const;\n`,
);
console.log('Brand synced from config.toml');
